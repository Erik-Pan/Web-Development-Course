function setupPage() {
    const navKeys = { HOME: "nav.home", GAMES: "nav.games", DEVLOG: "nav.devlog", "ABOUT ME": "nav.about", CONTACT: "nav.contact" };
    for (const link of document.querySelectorAll("header nav a")) {
        const key = navKeys[link.textContent.trim()];
        if (key) {
            link.dataset.i18n = key;
        }
    }

    const footer = document.querySelector("footer");
    if (footer) {
        for (const element of footer.querySelectorAll("p, h2, h3, span, label")) {
            if (element.textContent.trim() === "SUBSCRIBE") {
                element.dataset.i18n = "footer.subscribe";
            }
        }
        for (const input of footer.querySelectorAll("input[placeholder]")) {
            if (input.placeholder === "Your mail...") {
                input.dataset.i18nPlaceholder = "footer.email";
            }
        }
        const tagline = footer.querySelector('[data-i18n="footer.tagline"]');
        if (tagline) {
            tagline.removeAttribute("data-i18n");
        }
    }

    if (page === "ethereal-ascent.html") {
        setupGame("ethereal", "READY TO ENTER THE UNKNOWN?");
    }
    if (page === "space-call.html") {
        setupGame("space", "READY TO DEFEND THE CORE?");
    }
    if (page === "john-lemon.html") {
        setupGame("lemon", "CAN YOU ESCAPE THE HAUNTED MANSION?");
    }
    if (page === "a-new-chapter.html") {
        bind(".chapter-category", "article.category");
        bind(".chapter-heading h1", "article.title");
        bind(".chapter-heading time", "article.date");
        const paragraphs = document.querySelectorAll(".chapter-content > p:not(.chapter-ending)");
        for (let i = 0; i < paragraphs.length && i < 5; i++) {
            paragraphs[i].dataset.i18n = "article.p" + (i + 1);
        }
        bind(".chapter-ending", "article.ending");
        bindText(".chapter-navigation a", "BACK TO DEVLOG", "VOLVER AL DEVLOG");
    }
    if (page === "contact.html") {
        bind(".contact-section h1", "contact.title");
        bind(".contact-intro", "contact.intro");
        bind(".contact-details h2", "contact.heading");
        bind(".contact-details > p", "contact.description");
        bind(".contact-email", "contact.email");
    }
}

function translateUnmarkedText(language) {
    if (page !== "games.html" && page !== "devlog.html" && page !== "about-me.html") {
        return;
    }
    let root = document.querySelector("main");
    if (page === "games.html") {
        root = document.querySelector(".games-catalog");
    }
    if (!root) {
        return;
    }
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    let node = walker.nextNode();

    while (node) {
        if (node.parentElement && node.parentElement.closest("[data-i18n]")) {
            node = walker.nextNode();
            continue;
        }
        if (!originalTextNodes.has(node)) {
            originalTextNodes.set(node, node.nodeValue);
        }
        const original = originalTextNodes.get(node);
        const trimmed = original.replace(/\s+/g, " ").trim();
        let result = original;

        if (language === "es" && trimmed) {
            if (page === "games.html") {
                for (const [english, spanish] of catalogText) {
                    result = result.replaceAll(english, spanish);
                }
            } else {
                let translated = null;
                if (page === "devlog.html") {
                    translated = devlogText.get(trimmed);
                }
                if (page === "about-me.html") {
                    translated = aboutText.get(trimmed);
                    if (!translated) {
                        for (const [beginning, spanish] of aboutParagraphs) {
                            if (trimmed.startsWith(beginning)) {
                                translated = spanish;
                                break;
                            }
                        }
                    }
                    if (!translated && trimmed.includes("EK-Journey represents years of hard work")) {
                        translated = trimmed.replace(
                            "EK-Journey represents years of hard work, learning, determination and dreams.",
                            "EK-Journey es fruto de años de esfuerzo, aprendizaje y sueños por cumplir."
                        );
                    }
                }
                if (translated) {
                    const spacesBefore = original.match(/^\s*/)[0];
                    const spacesAfter = original.match(/\s*$/)[0];
                    result = spacesBefore + translated + spacesAfter;
                }
            }
        }
        node.nodeValue = result;
        node = walker.nextNode();
    }
}

function changeLanguage(language) {
    for (const element of document.querySelectorAll("[data-i18n]")) {
        if (!originalElements.has(element)) {
            originalElements.set(element, element.textContent);
        }
        const translation = translations.es[element.dataset.i18n];
        if (language === "es" && translation) {
            element.textContent = translation;
        } else {
            element.textContent = originalElements.get(element);
        }
    }

    for (const element of document.querySelectorAll("[data-i18n-placeholder]")) {
        if (!originalPlaceholders.has(element)) {
            originalPlaceholders.set(element, element.placeholder);
        }
        const translation = translations.es[element.dataset.i18nPlaceholder];
        if (language === "es" && translation) {
            element.placeholder = translation;
        } else {
            element.placeholder = originalPlaceholders.get(element);
        }
    }

    translateUnmarkedText(language);

    for (const [node, english, spanish] of specialTextNodes) {
        if (language === "es") {
            node.nodeValue = spanish;
        } else {
            node.nodeValue = english;
        }
    }

    if (page === "devlog.html") {
        const searchInput = document.querySelector("main input[placeholder]");
        if (searchInput) {
            if (!originalPlaceholders.has(searchInput)) {
                originalPlaceholders.set(searchInput, searchInput.placeholder);
            }
            if (language === "es") {
                searchInput.placeholder = "Buscar en el devlog...";
            } else {
                searchInput.placeholder = originalPlaceholders.get(searchInput);
            }
        }
    }

    document.documentElement.lang = language;
    try {
        localStorage.setItem("ekjourney-language", language);
    } catch (error) {
    }
}

