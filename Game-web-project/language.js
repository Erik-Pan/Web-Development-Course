const specialTextNodes = [];

function bind(selector, key) {
    const element = document.querySelector(selector);
    if (element) {
        element.dataset.i18n = key;
    }
}

function bindText(selector, english, spanish) {
    const element = document.querySelector(selector);
    if (!element) {
        return;
    }
    for (const node of element.childNodes) {
        if (node.nodeType === Node.TEXT_NODE && node.nodeValue.includes(english)) {
            specialTextNodes.push([node, node.nodeValue, node.nodeValue.replace(english, spanish)]);
            return;
        }
    }
}

function findHeading(text) {
    const headings = document.querySelectorAll("main h2");
    for (const heading of headings) {
        if (heading.textContent.trim() === text) {
            return heading;
        }
    }
    return null;
}

function setupGame(prefix, downloadTitle) {
    const synopsis = findHeading("SYNOPSIS");
    const information = findHeading("GAME INFORMATION");
    const screenshots = findHeading("SCREENSHOTS");
    const download = findHeading(downloadTitle);
    const paragraphs = synopsis?.parentElement.querySelectorAll("p");
    const items = document.querySelectorAll("main aside .detail-item");
    const downloadSection = download?.closest("section");

    if (synopsis) {
        synopsis.dataset.i18n = prefix + ".synopsisHeading";
    }
    if (paragraphs && paragraphs.length >= 2) {
        paragraphs[0].dataset.i18n = prefix + ".synopsis1";
        paragraphs[1].dataset.i18n = prefix + ".synopsis2";
    }
    if (information) {
        information.dataset.i18n = prefix + ".information";
    }
    if (screenshots) {
        screenshots.dataset.i18n = prefix + ".screenshots";
    }
    if (download) {
        download.dataset.i18n = prefix + ".downloadTitle";
    }
    if (downloadSection) {
        const description = downloadSection.querySelector("p");
        if (description) {
            description.dataset.i18n = prefix + ".downloadDescription";
        }
    }

    const labels = ["genre", "platform", "status", "engine"];
    for (let i = 0; i < items.length && i < labels.length; i++) {
        const heading = items[i].querySelector("h3");
        if (heading) {
            heading.dataset.i18n = prefix + "." + labels[i];
        }
    }
    if (items.length >= 3) {
        const genre = items[0].querySelector("p");
        const status = items[2].querySelector("p");
        if (genre) {
            genre.dataset.i18n = prefix + ".genreValue";
        }
        if (status) {
            if (prefix === "ethereal") {
                status.dataset.i18n = "ethereal.demo";
            } else {
                status.dataset.i18n = prefix + ".statusValue";
            }
        }
    }
    bindText("main a[download]", "DOWNLOAD", "DESCARGAR");
}

